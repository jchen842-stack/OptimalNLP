"""Brute-force oracle: exhaustively enumerate the formula space and check the search.

This validates the WHOLE pipeline end to end -- concept masks, the quantity helpers
(`compute_quantities` / `compute_disjoint_info`, which have no independent test otherwise),
the admissible heuristic, the frontier, and the returned optimum -- without writing a second
implementation of any of it. It only needs plain numpy set operations and a max.

Space enumerated (matching what the search can return):
  * a "length" is the number of LEAVES (formula.F.__len__ sums leaves; Not delegates to its
    child, so NOT is free);
  * NOT applies only to leaves (`formula.Not.__init__` asserts `isinstance(val, Leaf)`);
  * operators are AND and OR;
  * all tree shapes, since AND/OR are associative and commutative over masks.

So for K concepts the mask set is generated by: L1 = {c, ~c}, and
L(n) = { a op b : a in L(i), b in L(n-i), op in {AND, OR} }. Enumerating masks rather than
trees means associativity/commutativity collapse for free, and the MAX over the mask set is
identical to the max over the tree set.

This is a SUPERSET-or-equal of what the search explores, so:
  oracle_max >= search_result  always;
  oracle_max == search_result  iff the search really found the optimum.
A strict inequality means the search missed the optimum -- report it, do not adjust.
"""


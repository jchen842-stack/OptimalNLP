def enumerate_masks(dense, length):
    """All distinct token masks realisable by a formula of at most `length` leaves."""
    K, M = dense.shape
    lit = np.concatenate([dense, ~dense], axis=0)          # 2K literals
    levels = {1: lit}
    for n in range(2, length + 1):
        blocks = []
        for i in range(1, n):
            a, b = levels[i], levels[n - i]
            # (|a|, 1, M) op (1, |b|, M) -> (|a|*|b|, M), both operators
            blocks.append((a[:, None, :] & b[None, :, :]).reshape(-1, M))
            blocks.append((a[:, None, :] | b[None, :, :]).reshape(-1, M))
        levels[n] = np.unique(np.concatenate(blocks, axis=0), axis=0)
    return levels


def _max_iou(masks, neuron):
    inter = (masks & neuron).sum(axis=1).astype(np.float64)
    union = (masks | neuron).sum(axis=1).astype(np.float64)
    iou = np.divide(inter, union, out=np.zeros_like(inter), where=union > 0)
    return float(iou.max())


def best_iou_bruteforce(dense, neuron, length, chunk=64):
    """Max IoU over the entire enumerated space, by plain numpy. No search code involved.

    The top level is STREAMED rather than materialised: at length 4 the full level is
    ~1.26M masks x 24,199 elements = ~30 GB as bool. Streaming in chunks keeps peak memory
    at a few hundred MB and does not change the result, since only the max is needed.
    """
    levels = enumerate_masks(dense, length - 1) if length > 1 else {1: None}
    best, total = 0.0, 0
    for n, masks in (levels.items() if length > 1 else []):
        total += len(masks)
        best = max(best, _max_iou(masks, neuron))
    if length == 1:
        lit = np.concatenate([dense, ~dense], axis=0)
        return _max_iou(lit, neuron), len(lit)

    M = dense.shape[1]
    for i in range(1, length):
        a, b = levels[i], levels[length - i]
        for s in range(0, len(a), chunk):
            blk = a[s:s + chunk]
            both = np.concatenate([
                (blk[:, None, :] & b[None, :, :]).reshape(-1, M),
                (blk[:, None, :] | b[None, :, :]).reshape(-1, M)], axis=0)
            total += len(both)
            best = max(best, _max_iou(both, neuron))
    return best, total


def run_case(label, dense, concepts, neuron, length):
    oracle, n_forms = best_iou_bruteforce(dense, neuron, length)
    res = rts.run_one(dense, neuron, length, cap=200000, time_budget=1500,
                      beam_cap=None, concepts=concepts)
    search = res["best_iou"]
    # run_one rounds to 4dp for the CSV; recover full precision from the counts it kept.
    exact = res["n_inter"] / (res["n_fires"] + int(neuron.sum()) - res["n_inter"])
    ok = abs(exact - oracle) < 1e-12
    print(f"\n--- {label} (length {length}) ---")
    print(f"  masks evaluated           : {n_forms:,} (top level streamed, not deduped)")
    print(f"  brute-force max IoU       : {oracle!r}")
    print(f"  search best_iou           : {exact!r}")
    print(f"  search formula            : {res['formula']}")
    print(f"  |difference|              : {abs(exact - oracle):.3e}")
    print(f"  {'MATCH' if ok else 'MISMATCH -- STOP, do not adjust anything'}")
    if exact > oracle + 1e-12:
        print("  !! search exceeded the oracle: the enumeration is not a superset")
    return ok


